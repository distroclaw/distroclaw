// Writes THIRD_PARTY_NOTICES.md: the licences of everything a release build ships.
//
//   node scripts/third-party-notices.mjs [--check] [--target aarch64-apple-darwin] [--npm-root <dir>]
//
// Covers the Rust crates compiled into the app for the target (normal dependencies only), the
// npm packages the frontend bundles (production dependencies) and the bundled engine's licence
// files (licenses/engine; for Windows targets licenses/engine-windows). Each distinct licence text appears
// once, with the components that use it. --check fails if the committed file is out of date.
// The committed file is the macOS one; Windows builds write theirs before building.

import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const target = args.includes("--target") ? args[args.indexOf("--target") + 1] : "aarch64-apple-darwin";
/** Where package-lock.json and node_modules are; another checkout with the same lockfile works. */
const npmRoot = args.includes("--npm-root") ? path.resolve(args[args.indexOf("--npm-root") + 1]) : root;
const outFile = path.join(root, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)([-_.].*)?$/i;

/** Distinct licence texts, by hash: { text, users: Set<string> }. */
const texts = new Map();
/** Components without a licence file of their own: name -> SPDX expression. */
const declaredOnly = new Map();

function addText(text, user) {
  const clean = text.replace(/\r\n/g, "\n").trim();
  const key = crypto.createHash("sha256").update(clean).digest("hex");
  if (!texts.has(key)) texts.set(key, { text: clean, users: new Set() });
  texts.get(key).users.add(user);
}

function addDir(dir, user, declared) {
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort() : [];
  for (const f of files) addText(fs.readFileSync(path.join(dir, f), "utf8"), user);
  if (!files.length) declaredOnly.set(user, declared || "unknown");
}

// Rust: crates reachable from the app through normal dependencies on the target platform.
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", target, "--locked"], {
    cwd: path.join(root, "src-tauri"),
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const app = meta.resolve.root;
const seen = new Set([app]);
const queue = [app];
while (queue.length) {
  for (const dep of nodes.get(queue.shift()).deps) {
    const normal = dep.dep_kinds.some((k) => k.kind === null);
    if (normal && !seen.has(dep.pkg)) {
      seen.add(dep.pkg);
      queue.push(dep.pkg);
    }
  }
}
seen.delete(app);
let crates = 0;
for (const id of seen) {
  const p = byId.get(id);
  if (p.source === null) continue; // a workspace crate of our own
  crates++;
  const who = p.authors?.length ? `, by ${p.authors.map((a) => a.replace(/\s*<[^>]*>/, "")).join(", ")}` : "";
  const src = p.repository ? `, source: ${p.repository}` : `, source: https://crates.io/crates/${p.name}/${p.version}`;
  addDir(path.dirname(p.manifest_path), `${p.name} ${p.version} (Rust)`, `${p.license}${who}${src}`);
}

// npm: production dependencies, as installed.
const lock = JSON.parse(fs.readFileSync(path.join(npmRoot, "package-lock.json"), "utf8"));
let packages = 0;
for (const [where, p] of Object.entries(lock.packages)) {
  if (!where || p.dev) continue;
  packages++;
  const name = where.replace(/^.*node_modules\//, "");
  const lic = typeof p.license === "object" ? p.license.type : p.license;
  addDir(path.join(npmRoot, where), `${name} ${p.version} (npm)`, lic);
}

// The bundled AI engine: its licence files are kept in licenses/engine, matching the pinned
// engine version, so the output does not depend on what is staged on this machine. The Windows
// engine is a different build (CPU and Vulkan, Windows runtime libraries): licenses/engine-windows.
const engineFolder = target.includes("windows") ? "engine-windows" : "engine";
const engineDir = path.join(root, "licenses", engineFolder);
for (const f of fs.readdirSync(engineDir).sort()) {
  const part = f.replace(/[_.-]?(licen[sc]e|notice).*$/i, "").replace(/_/g, " ").toLowerCase();
  addText(fs.readFileSync(path.join(engineDir, f), "utf8"), `AI engine: ${part}`);
}

const sorted = [...texts.values()].sort((a, b) => [...a.users][0].localeCompare([...b.users][0]));
let md = `# Third-party notices\n\nDistroClaw includes the software listed below. Each component is licensed by its authors under the terms shown with it.\n\nGenerated by scripts/third-party-notices.mjs for ${target}: ${crates} Rust crates, ${packages} npm packages and the bundled AI engine (licenses/${engineFolder}).\n\nAI models are downloaded separately and come with their own licence. The app shows it in Settings > Model.\n`;
for (const { text, users } of sorted) {
  md += `\n---\n\n**Used by:** ${[...users].sort().join(", ")}\n\n\`\`\`text\n${text.replace(/```/g, "'''")}\n\`\`\`\n`;
}
if (declaredOnly.size) {
  md += `\n---\n\n## Components without a licence file of their own\n\nThese packages declare their licence in their metadata; the standard text of that licence applies. Components under the Mozilla Public License 2.0 are used unmodified; their source code is available at the address given.\n\n`;
  for (const [name, lic] of [...declaredOnly].sort()) md += `- ${name}: ${lic}\n`;
}

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== md) {
    console.error("THIRD_PARTY_NOTICES.md is out of date; run node scripts/third-party-notices.mjs");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  fs.writeFileSync(outFile, md);
  console.log(
    `Wrote ${path.relative(root, outFile)}: ${texts.size} licence texts, ${declaredOnly.size} declared-only components, ${(md.length / 1024).toFixed(0)} KB.`,
  );
}
