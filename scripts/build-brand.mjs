#!/usr/bin/env node
// Generates every logo file from one master, brand/DistroClaw_Logo_Transparent_Vector.svg
// (the robot and the DistroClaw wordmark, with white letters for dark backgrounds):
//
//   src/assets/logo-mark.svg   the robot alone, square, for the desktop app's Logo component
//   app-icon.svg               1024px macOS-grid icon (feed to `npx tauri icon app-icon.svg`)
//
// With --website <folder> (a checkout of the landing page's repository), also its logos:
//
//   assets/logo-dark.svg       robot + wordmark, cropped to the artwork, for dark backgrounds
//   assets/logo-light.svg      the same with dark "Distro" letters, for light backgrounds
//   assets/emblem.svg          the robot alone, square (favicon, avatar, banner)
//
// To change the logo, replace the master and run `npm run brand -- --website <folder>`, then
// `npx tauri icon app-icon.svg`.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MASTER = "brand/DistroClaw_Logo_Transparent_Vector.svg";
const master = fs.readFileSync(path.join(root, MASTER), "utf8");

// Letter color on light backgrounds; matches the landing page's light-theme text.
const PAPER_TEXT = "#17140f";

/** The text between `start` and `end` in the master; fails loudly if the master's structure changed. */
function slice(start, end, { inclusive = true } = {}) {
  const i = master.indexOf(start);
  const j = master.indexOf(end, i + start.length);
  if (i < 0 || j < 0) throw new Error(`${MASTER}: expected ${start} … ${end}`);
  return inclusive ? master.slice(i, j) : master.slice(i + start.length, j);
}

const defs = slice("<defs>", "</defs>", { inclusive: false }).trim();
const robot = slice('<g id="robot-icon"', '<g id="wordmark"').trim();
const wordmark = slice('<g id="wordmark"', "</svg>").trim();

/** Bounds of the absolute M/L path data in `fragment`, shifted by (dx, dy). */
function bounds(fragment, dx = 0, dy = 0) {
  const b = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity };
  for (const [, d] of fragment.matchAll(/ d="([^"]*)"/g)) {
    if (/[^MLZ\d\s,.-]/.test(d)) throw new Error(`${MASTER}: only absolute M/L/Z paths are supported`);
    for (const [, x, y] of d.matchAll(/(-?[\d.]+)[ ,](-?[\d.]+)/g)) {
      b.x0 = Math.min(b.x0, +x + dx);
      b.y0 = Math.min(b.y0, +y + dy);
      b.x1 = Math.max(b.x1, +x + dx);
      b.y1 = Math.max(b.y1, +y + dy);
    }
  }
  return b;
}

const [tx, ty] = robot.match(/translate\((-?[\d.]+)[ ,](-?[\d.]+)\)/).slice(1).map(Number);
const robotBox = bounds(robot, tx, ty);
const wordBox = bounds(wordmark);
const fullBox = {
  x0: Math.min(robotBox.x0, wordBox.x0),
  y0: Math.min(robotBox.y0, wordBox.y0),
  x1: Math.max(robotBox.x1, wordBox.x1),
  y1: Math.max(robotBox.y1, wordBox.y1),
};

/** A square around the robot with `pad` units of room on its longer side. */
function robotSquare(pad) {
  const size = Math.max(robotBox.x1 - robotBox.x0, robotBox.y1 - robotBox.y0) + 2 * pad;
  const cx = (robotBox.x0 + robotBox.x1) / 2;
  const cy = (robotBox.y0 + robotBox.y1) / 2;
  return { x: cx - size / 2, y: cy - size / 2, w: size, h: size };
}

const r = (n) => Math.round(n * 10) / 10;

function svg({ x, y, w, h }, note, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${r(w)}" height="${r(h)}" viewBox="${r(x)} ${r(y)} ${r(w)} ${r(h)}" role="img" aria-label="DistroClaw">
<!-- Generated by scripts/build-brand.mjs from ${MASTER}. ${note} -->
<title>DistroClaw</title>
<defs>
${defs}
</defs>
${body}
</svg>
`;
}

// Room for the outline below and antialiasing.
const PAD = 8;
const full = { x: fullBox.x0 - PAD, y: fullBox.y0 - PAD, w: fullBox.x1 - fullBox.x0 + 2 * PAD, h: fullBox.y1 - fullBox.y0 + 2 * PAD };

/** `fragment` with `from` replaced once; fails loudly if the master no longer contains it. */
function swap(fragment, from, to) {
  if (!fragment.includes(from)) throw new Error(`${MASTER}: expected ${from}`);
  return fragment.replace(from, to);
}

const lightWordmark = swap(wordmark, 'fill="url(#wordWhite)"', `fill="${PAPER_TEXT}"`);
// The white shell fades into light backgrounds; an even outline along the dark silhouette keeps
// the robot's shape (and its antenna) readable there. On dark backgrounds it is invisible.
const outlinedRobot = swap(
  robot,
  '<path id="outer-silhouette"',
  '<path id="outer-silhouette" stroke="#05050b" stroke-width="8" stroke-linejoin="round"',
);

/** macOS Big Sur grid: 824px tile at 100px inset on a 1024 canvas; the robot fills about 62% of the tile's width. */
function appIconSvg() {
  const box = robotSquare(0);
  const scale = (824 * 0.62) / box.w;
  const cx = (robotBox.x0 + robotBox.x1) / 2;
  const cy = (robotBox.y0 + robotBox.y1) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
<!-- Generated by scripts/build-brand.mjs from ${MASTER}. -->
<defs>
${defs}
  <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#1f1f25"/>
    <stop offset="1" stop-color="#0b0b0d"/>
  </linearGradient>
  <radialGradient id="ember" cx="0.5" cy="1" r="0.75">
    <stop offset="0" stop-color="#ff6b1a" stop-opacity="0.55"/>
    <stop offset="1" stop-color="#ff6b1a" stop-opacity="0"/>
  </radialGradient>
  <clipPath id="tile-shape"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>
  <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
    <feDropShadow dx="0" dy="12" stdDeviation="14" flood-color="#000" flood-opacity="0.35"/>
  </filter>
</defs>
<g filter="url(#shadow)">
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#tile)"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#ember)" clip-path="url(#tile-shape)"/>
  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" fill="none" stroke="#fff" stroke-opacity="0.1" stroke-width="3"/>
</g>
<g transform="translate(512 ${512 + 10}) scale(${scale.toFixed(5)}) translate(${-cx} ${-cy})">
${robot}
</g>
</svg>
`;
}

const args = process.argv.slice(2);
const website = args.includes("--website") ? path.resolve(args[args.indexOf("--website") + 1]) : null;
const out = {
  "src/assets/logo-mark.svg": svg(robotSquare(PAD), "The robot alone, for the desktop app.", outlinedRobot),
  "app-icon.svg": appIconSvg(),
};
if (website) {
  Object.assign(out, {
    [path.join(website, "assets/logo-dark.svg")]: svg(full, "Robot and wordmark for dark backgrounds.", `${robot}\n${wordmark}`),
    [path.join(website, "assets/logo-light.svg")]: svg(full, 'For light backgrounds: dark "Distro" letters, outlined robot.', `${outlinedRobot}\n${lightWordmark}`),
    [path.join(website, "assets/emblem.svg")]: svg(robotSquare(PAD), "The robot alone; reads on light and dark backgrounds.", outlinedRobot),
  });
}
for (const [file, content] of Object.entries(out)) {
  const target = path.resolve(root, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
  console.log(`brand -> ${path.relative(root, target)}`);
}
const ratio = (fullBox.x1 - fullBox.x0 + 2 * PAD) / (fullBox.y1 - fullBox.y0 + 2 * PAD);
console.log(`logo aspect ratio ${ratio.toFixed(3)}:1 (e.g. ${Math.round(52 * ratio)}×52)`);
